/* =========================================================
   IMAGE URL
========================================================= */

function imageUrl(name) {

    return WIKI_IMAGE +
        encodeURIComponent(name + ".png");

}


/* =========================================================
   STATE
========================================================= */

let filteredItems = [...ITEMS];

const selected = new Set();


/* =========================================================
   GET ELEMENTS
========================================================= */

const grid =
    document.getElementById("lootGrid");

const search =
    document.getElementById("searchInput");

const category =
    document.getElementById("categoryFilter");

const rarity =
    document.getElementById("rarityFilter");

const sort =
    document.getElementById("sortSelect");

const itemCount =
    document.getElementById("itemCount");

const selectedCount =
    document.getElementById("selectedCount");

const empty =
    document.getElementById("emptyState");


/* =========================================================
   SAFETY CHECK
========================================================= */

if (
    !grid ||
    !search ||
    !category ||
    !rarity ||
    !sort
) {

    console.error(
        "ARC Raiders Loot Table: required HTML elements were not found."
    );

}


/* =========================================================
   CATEGORIES
========================================================= */

function buildCategories() {

    const categories = [
        ...new Set(
            ITEMS.map(item => item.category)
        )
    ].sort();

    categories.forEach(name => {

        const option =
            document.createElement("option");

        option.value = name;

        option.textContent = name;

        category.appendChild(option);

    });

}


/* =========================================================
   FILTER
========================================================= */

function filterItems() {

    const text =
        search.value
            .trim()
            .toLowerCase();

    const cat =
        category.value;

    const rar =
        rarity.value;


    filteredItems =
        ITEMS.filter(item => {

            const matchesText =
                !text ||
                item.name
                    .toLowerCase()
                    .includes(text);

            const matchesCategory =
                cat === "all" ||
                item.category === cat;

            const matchesRarity =
                rar === "all" ||
                item.rarity
                    .toLowerCase() === rar;

            return (
                matchesText &&
                matchesCategory &&
                matchesRarity
            );

        });


    sortItems();

}


/* =========================================================
   SORT
========================================================= */

function sortItems() {

    const type =
        sort.value;

    const rarityOrder = {

        Common: 1,
        Uncommon: 2,
        Rare: 3,
        Epic: 4,
        Legendary: 5

    };


    filteredItems.sort((a, b) => {

        if (type === "rarity") {

            return (
                rarityOrder[b.rarity] -
                rarityOrder[a.rarity]
            );

        }


        if (type === "value") {

            return (
                (b.value || 0) -
                (a.value || 0)
            );

        }


        if (type === "category") {

            return a.category.localeCompare(
                b.category
            );

        }


        return a.name.localeCompare(
            b.name
        );

    });


    render();

}


/* =========================================================
   RENDER
========================================================= */

function render() {

    if (!grid)
        return;


    grid.innerHTML = "";


    itemCount.textContent =
        filteredItems.length;


    selectedCount.textContent =
        selected.size;


    empty.classList.toggle(
        "hidden",
        filteredItems.length > 0
    );


    filteredItems.forEach(item => {

        const card =
            document.createElement("article");


        /* =================================================
           THIS IS THE IMPORTANT PART
        ================================================= */

        card.className =
            "loot-card" +
            (
                selected.has(item.name)
                    ? " selected"
                    : ""
            );


        card.dataset.rarity =
            item.rarity.toLowerCase();


        /* =================================================
           IMAGE
        ================================================= */

        
        const image =
            document.createElement("img");

        image.src =
            imageUrl(item.name);

        image.alt =
            item.name;

        image.loading = "lazy";
        image.decoding = "async";
        image.width = 124;
        image.height = 124;

        image.onerror = function () {

            this.style.opacity = ".15";

        };


        const imageWrap =
            document.createElement("div");

        imageWrap.className =
            "loot-card__image";

        imageWrap.appendChild(
            image
        );


        /* =================================================
           PRICE BAR
        ================================================= */

        const info =
            document.createElement("div");

        info.className =
            "loot-card__info";


        const price =
            document.createElement("span");

        price.className =
            "loot-card__price";


        price.textContent =
            formatValue(item.value);


        info.appendChild(
            price
        );


        /* =================================================
           CARD
        ================================================= */

        card.appendChild(
            imageWrap
        );

        card.appendChild(
            info
        );


        /* =================================================
           CLICK
        ================================================= */

        card.addEventListener(
            "click",
            () => {

                toggleItem(item);

            }
        );


        grid.appendChild(
            card
        );

    });

}


/* =========================================================
   SELECTION
========================================================= */

function toggleItem(item) {

    if (
        selected.has(item.name)
    ) {

        selected.delete(
            item.name
        );

    } else {

        selected.add(
            item.name
        );

    }


    render();

}


/* =========================================================
   VALUE
========================================================= */

function formatValue(value) {

    if (
        value === null ||
        value === undefined
    ) {

        return "—";

    }


    return "$" +
        Number(value)
            .toLocaleString();

}


/* =========================================================
   EVENTS
========================================================= */

if (search) {

    search.addEventListener(
        "input",
        filterItems
    );

}


if (category) {

    category.addEventListener(
        "change",
        filterItems
    );

}


if (rarity) {

    rarity.addEventListener(
        "change",
        filterItems
    );

}


if (sort) {

    sort.addEventListener(
        "change",
        sortItems
    );

}


/* =========================================================
   INIT
========================================================= */

function initLootTable() {

    buildCategories();

    filterItems();

}


/* =========================================================
   START
========================================================= */

if (
    document.readyState === "loading"
) {

    document.addEventListener(
        "DOMContentLoaded",
        initLootTable
    );

} else {

    initLootTable();

}